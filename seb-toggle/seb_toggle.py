def detect_and_load(path):
    """sec 3.1 - format detection, first match wins. Raises Refused with a clean message."""
    p = Path(path)
    if not p.exists():
        raise Refused("no such file: %s" % p)
    blob = p.read_bytes()
    head = blob[:4]

    if head in SEB_MAGIC:
        raise Refused(
            "SEB binary container detected (prefix %r, %d bytes).\n"
            "  This is the encrypted/compressed container handled by\n"
            "  DataFormats/BinaryParser.cs + GZipCompressor.cs, not a plist.\n"
            "  Out of scope - refusing." % (head.decode("ascii", "replace"), len(blob))
        )

    try:
        with p.open("rb") as fh:
            data = plistlib.load(fh, fmt=None)
    except Exception as exc:
        raise Refused(
            "not a plist and not a recognized SEB container.\n"
            "  leading bytes (hex): %s\n"
            "  parser error: %s: %s" % (blob[:16].hex(" "), type(exc).__name__, exc)
        )

    if not isinstance(data, dict):
        raise Refused("plist root is %s, expected a dictionary" % type(data).__name__)
    return data, len(blob)


def check_encryption(data):
    """sec 3.2 - a key read, not a format inspection."""
