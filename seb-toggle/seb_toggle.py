def build_unlock(data):
    """Return {key: permissive_value} for every key this profile can move."""
    intended = {}
    for k, v in UNLOCK_BOOL.items():
        if isinstance(data.get(k), bool) and data[k] != v:
            intended[k] = v
    for k, label in UNLOCK_ENUM.items():
        space = ENUM_SPACES.get(k)
        if k in data and space and label in space["to"]:
            v = space["to"][label]
            if data[k] != v:
                intended[k] = v
    for k in UNLOCK_LISTS:
        cur = data.get(k)
        if isinstance(cur, list) and cur:
            new = []
            off = 0
            for e in cur:
                if isinstance(e, dict) and e.get("active"):
                    e = dict(e)
                    e["active"] = False
                    off += 1
                new.append(e)
            if off:
                intended[k] = new
    return intended

