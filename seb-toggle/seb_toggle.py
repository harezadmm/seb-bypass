def _box(lines, title=None, color=None, width=None):
    color = color or cyan
    width = width or WIDTH
    out = [color(TL + H * (width - 2) + TR)]
    if title:
        out.append(color(V) + " " + bold(_pad(title, width - 4)) + " " + color(V))
        out.append(color(LT + H * (width - 2) + RT))
    for ln in lines:
        out.append(color(V) + " " + _pad(_clip(ln, width - 4), width - 4) + " " + color(V))
    out.append(color(BL + H * (width - 2) + BR))
    return "\n".join(out)


def _clip(s, w):
    if len(_strip(s)) <= w:
        return s
    return _strip(s)[:w - 3] + "..."


def _fmt_bytes(n):
    if n is None:
        return "-"
    if n < 1024:
        return "%d B" % n
    if n < 1048576:
        return "%.1f KB" % (n / 1024.0)
    return "%.1f MB" % (n / 1048576.0)


def _bar(n, total, width=30):
    if total <= 0:
        return ""
    filled = int(round(width * n / float(total)))
    ch, em = ("\u2588", "\u2591") if UNI else ("#", ".")
    return ch * filled + em * (width - filled)


