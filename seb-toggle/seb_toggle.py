# --------------------------------------------------------------------------- registry

class Registry:
    def __init__(self, path):
        import json
        if not path.exists():
            raise SystemExit("registry missing: %s - run build_registry.py first" % path)
        raw = json.loads(path.read_text(encoding="utf-8"))
        self.keys = raw["keys"]              # wire key -> Keys.cs category path
        self.dispatch = raw["dispatch"]      # wire key -> Map* method
        self.methods = raw["methods"]        # Map* method -> {file, prop, expr, inverted}
        self.defaults = raw["defaults"]      # property path -> default literal
        self.categories = raw["categories"]  # category path -> [wire keys]
        self.collisions = raw.get("const_collisions", {})
        self.key_cat = {}
        for cat, ks in self.categories.items():
            for k in ks:
                self.key_cat.setdefault(k, cat)

    def mapper(self, key):
        return self.methods.get(self.dispatch.get(key, ""))

    def default_literal(self, key):
        m = self.mapper(key)
        return self.defaults.get(m["prop"]) if m else None

    def category(self, key):
        return self.key_cat.get(key, "Keys.Unknown")

    def is_known(self, key):
        return key in self.keys


def parse_default_bool(literal):
    """sec 2.4 - Literals in LoadDefaultSettings() are already PROPERTY-space values.

    Compare propval against this directly. Never invert the default.
    Returns True/False, or None when the literal is absent or non-boolean.
    """
    if literal is None:
        return None
    s = literal.strip()
    if s.startswith('"') and s.endswith('"'):
        s = s[1:-1]
    if s == "true":
        return True
    if s == "false":
        return False
    return None


