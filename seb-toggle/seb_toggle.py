def effective_propval(raw, inverted):
    """sec 4.1 - config flag -> property value. Toggle logic never needs this;
    it exists so the DEFAULT column can be compared like-for-like."""
    if isinstance(raw, bool):
        return (not raw) if inverted else raw
    return raw


def classify(key, reg):
    """sec 5.1 - returns a row dict for one key present in the file."""
    cat = reg.category(key)
    m = reg.mapper(key)
    raw = None  # filled by caller
    row = {
        "key": key,
        "category": cat,
        "known": reg.is_known(key),
        "mapper": reg.dispatch.get(key),
        "prop": m["prop"] if m else None,
        "inverted": bool(m["inverted"]) if m else False,
        "default_literal": reg.default_literal(key),
    }
    return row


def classify_value(row, raw, reg):
    """sec 5.1 - assign STATUS / EFFECTIVE / DEFAULT given the raw value."""
    row["raw"] = raw
    dv = parse_default_bool(row["default_literal"])
    row["default_bool"] = dv

    if not row["known"]:
        row["status"] = "IGNORED-BY-3.10.2"
        row["effective"] = "n/a"
        row["default"] = "n/a"
        return row

    if isinstance(raw, bool):
        # sec 5.2 - a bool-valued enum key renders its semantic label; the raw
        # bool is the wire form, not the meaning. Non-enum bools stay permits/restricts.
        space = ENUM_SPACES.get(row["key"])
        if space and raw in space["from"]:
            row["effective"] = space["from"][raw]
        else:
            row["effective"] = "permits" if raw else "restricts"
        if dv is None:
            row["default"] = "n/a"
            # absence of a default is not evidence of an edit (sec 5.1)
            row["status"] = "PERMISSIVE" if raw else "RESTRICTION"
        else:
            propval = effective_propval(raw, row["inverted"])
            if propval == dv:
                row["default"] = "SEB default"
                row["status"] = "PERMISSIVE" if raw else "RESTRICTION SEB default"
            else:
                row["default"] = "author-imposed"
                row["status"] = "PERMISSIVE" if raw else "RESTRICTION author-imposed"
        return row

    row["status"] = "MODE-SELECTOR"
    space = ENUM_SPACES.get(row["key"])
    if space:
        row["effective"] = space["from"].get(raw, "unknown(%r)" % (raw,))
    elif isinstance(raw, list):
        row["effective"] = "list[%d]" % len(raw)
    elif isinstance(raw, dict):
        row["effective"] = "dict[%d]" % len(raw)
    elif isinstance(raw, bytes):
        row["effective"] = "base64:" + base64.b64encode(raw).decode()[:16] + "..."
    else:
        row["effective"] = repr(raw)[:28]
    row["default"] = "n/a"
    return row


def scan(data, reg):
    """sec 5 - the full scan pass over one config."""
    rows = []
    for key in sorted(data):
        row = classify(key, reg)
        classify_value(row, data[key], reg)
        rows.append(row)

    absent = []
    for key in sorted(reg.keys):
        if key not in data:
            m = reg.mapper(key)
            absent.append({
                "key": key, "category": reg.category(key), "known": True,
                "mapper": reg.dispatch.get(key),
                "prop": m["prop"] if m else None,
                "inverted": bool(m["inverted"]) if m else False,
                "default_literal": reg.default_literal(key),
                "status": "ABSENT-DEFAULTED",
                "raw": None,
                "effective": "CLR false (constructor sets nothing)",
                "default": reg.default_literal(key) or "n/a",
            })
    return rows, absent


def counts(rows, absent):
    c = {
        "RESTRICTION author-imposed": 0, "RESTRICTION SEB default": 0,
        "RESTRICTION": 0, "PERMISSIVE": 0, "MODE-SELECTOR": 0,
        "IGNORED-BY-3.10.2": 0, "ABSENT-DEFAULTED": len(absent),
    }
    for r in rows:
        c[r["status"]] = c.get(r["status"], 0) + 1
    return c


