def fmt_raw(v):
    if isinstance(v, bytes):
        return "base64:%s..." % base64.b64encode(v).decode()[:16]
    if isinstance(v, list):
        return "[%d]" % len(v)
    if isinstance(v, dict):
        return "{%d}" % len(v)
    return repr(v)


