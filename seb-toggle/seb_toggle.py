# --------------------------------------------------------------------------- sec 6

def build_menu(rows, reg, category=None):
    """Toggleable = present in file AND recognized AND boolean."""
    entries = [r for r in rows if r["known"] and isinstance(r["raw"], bool)]
    if category:
        entries = [r for r in entries if r["category"] == category]
    entries.sort(key=lambda r: (r["category"], r["key"]))
    return entries


def print_menu(entries):
    if RICH:
        return print_menu_rich(entries)
    print("TOGGLE MENU  (grouped by registry category)")
    print("-" * 100)
    last = None
    for i, r in enumerate(entries, 1):
        if r["category"] != last:
            print("\n  [%s]" % r["category"])
            last = r["category"]
        print("   %3d  %-38s %-6s %-10s %-16s %s" % (
            i, r["key"], str(r["raw"]), "permits" if r["raw"] else "restricts",
            r["default"], (r["prop"] or "")[:34]))
    print()
    print("  Enter: 3 | 3,7,12 | 12-18 | all | none | unlock | done")
    print("  Toggling flips a boolean to the opposite state (sec 4.1: raw value, direct polarity).")


def parse_selection(text, n):
    text = text.strip().lower()
    if text in ("done", ""):
        return []
    if text == "all":
        return list(range(1, n + 1))
    if text == "none":
        return []
    picked = []
    junk = []
    for part in text.split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            a, b = part.split("-", 1)
            try:
                picked.extend(range(int(a), int(b) + 1))
            except ValueError:
                junk.append(part)
        else:
            try:
                picked.append(int(part))
            except ValueError:
                junk.append(part)
    if junk:
        print("  not a number or range: %s" % junk)
        return []
    bad = [p for p in picked if p < 1 or p > n]
    if bad:
        print("  out of range: %s" % bad)
        return []
    return sorted(set(picked))


def interactive_toggle(entries, data):
    """Returns {key: new_value}. Only booleans are offered here."""
    if not entries:
        print("no toggleable boolean keys in scope.")
        return {}
    print_menu(entries)
    intended = {}
    while True:
        try:
            raw = input("select> ")
        except EOFError:
            break
        if raw.strip().lower() == "done":
            break
        if raw.strip().lower() in ("unlock", "u"):
            u = build_unlock(data)
            if not u:
                print("  nothing to unlock - this config is already open.")
                continue
            intended.update(u)
            print("  unlock profile queued: %d keys" % len(u))
            continue
        sel = parse_selection(raw, len(entries))
        if not sel:
            continue
        print()
        for i in sel:
            e = entries[i - 1]
            new = not e["raw"]
            if RICH:
                print("   " + yellow("~") + " " + bold(_ljust(e["key"], 36)) + " "
                      + (green(str(e["raw"])) if e["raw"] else red(str(e["raw"])))
                      + " " + dim("->") + " "
                      + (green(str(new)) if new else red(str(new))))
            else:
                print("   %-38s %s -> %s" % (e["key"], e["raw"], new))
            intended[e["key"]] = new
        print()
        more = input("add more? [y/N] ").strip().lower()
        if more != "y":
            break
    return intended


# --------------------------------------------------------------------------- sec 7

def write_output(data, intended, src_path, out_path, add_missing, reg):
    """sec 7 - write to a new file, then verify. Never in place."""
    out = dict(data)
    added = []
    for k, v in intended.items():
        if k not in out:
            added.append(k)
    out.update(intended)

    out_path = Path(out_path)
    with out_path.open("wb") as fh:
        plistlib.dump(out, fh, fmt=plistlib.FMT_XML)

    return out_path, added


def verify(src, src_path, out_path, intended, add_missing):
    """sec 7 - the five assertions. Returns (ok, errors, stats)."""
    with open(out_path, "rb") as fh:
        produced = plistlib.load(fh)
    errors = []
    src_keys, out_keys = set(src), set(produced)

    # 1 - every intended key changed to the intended value
    for k, v in intended.items():
        if produced.get(k) != v:
            errors.append("A1 intended value not applied: %s expected %r got %r"
                          % (k, v, produced.get(k)))

    # 2 - no other key changed
    for k in sorted(src_keys & out_keys):
        if k not in intended and src[k] != produced[k]:
            errors.append("A2 key changed unexpectedly: %s (%r -> %r)"
                          % (k, src[k], produced[k]))

    # 3 - no key added unless --add-missing
    added = sorted(out_keys - src_keys)
    if added and not add_missing:
        errors.append("A3 keys added without --add-missing: %s" % added)
    removed = sorted(src_keys - out_keys)
    if removed:
        errors.append("A2 keys removed: %s" % removed)

    # 4 - startURL and every non-selected key identical
    if src.get("startURL") != produced.get("startURL"):
        errors.append("A4 startURL changed: %r -> %r"
                      % (src.get("startURL"), produced.get("startURL")))
    for k in sorted(src_keys & out_keys):
        if k not in intended and src[k] != produced[k]:
            errors.append("A4 non-selected key differs: %s" % k)

    stats = {
        "src_bytes": Path(src_path).stat().st_size,
        "out_bytes": out_path.stat().st_size,
        "src_keys": len(src_keys),
        "out_keys": len(out_keys),
        "added": added,
    }
    return (not errors), errors, stats


# --------------------------------------------------------------------------- diff

def diff_configs(a_path, b_path, reg):
    a, _ = detect_and_load(a_path)
    b, _ = detect_and_load(b_path)
    keys = sorted(set(a) | set(b))
    diffs = [(k, a.get(k, "<absent>"), b.get(k, "<absent>")) for k in keys if a.get(k) != b.get(k)]
    if RICH:
        _diff_rich(a_path, b_path, diffs, reg)
    else:
        print("diff: %s  vs  %s" % (a_path, b_path))
        print("  differing keys: %d" % len(diffs))
        for k, va, vb in diffs:
            prop = reg.methods.get(reg.dispatch.get(k, ""), {}).get("prop", "(unmapped)")
            print("    %-34s %-28s -> %-28s  %s" % (k, fmt_raw(va)[:28], fmt_raw(vb)[:28], prop))
    return diffs


# --------------------------------------------------------------------------- main

def parse_set_arg(s, reg):
    if "=" not in s:
        raise SystemExit("--set expects key=value, got %r" % s)
    k, v = s.split("=", 1)
    k, v = k.strip(), v.strip()
    if k in ENUM_SPACES and v in ENUM_SPACES[k]["to"]:
        return k, ENUM_SPACES[k]["to"][v]
    low = v.lower()
    if low == "true":
        return k, True
    if low == "false":
        return k, False
    if low == "allow":
        return k, True
    if low == "block":
        return k, False
    try:
        return k, int(v)
    except ValueError:
        return k, v


def main():
    ap = argparse.ArgumentParser(
        prog="seb_toggle.py",
        description="Scan and toggle Safe Exam Browser .seb config restrictions.")
    ap.add_argument("file", help="input .seb config")
    ap.add_argument("--scan", action="store_true", help="report only, no prompt")
    ap.add_argument("--only-ignored", action="store_true", help="the legacy keys and nothing else")
    ap.add_argument("-c", "--category", help="narrow the toggle menu to one registry category")
    ap.add_argument("-s", "--set", action="append", default=[], metavar="KEY=VALUE",
                    help="non-interactive toggle; repeatable")
    ap.add_argument("-a", "--add-missing", action="store_true",
                    help="allow writing keys the file does not contain")
    ap.add_argument("-y", "--yes", action="store_true", help="skip the confirm prompt")
    ap.add_argument("-o", "--out", help="default: <stem>.modified.seb")
    ap.add_argument("--diff", metavar="OTHER", help="compare two configs and report differing keys")
    ap.add_argument("--unlock-all", action="store_true",
                    help="queue the full relaxation profile (screen capture, keyboard, VM, app blocks, ...)")
    ap.add_argument("--no-color", action="store_true", help="disable ANSI colors")
    args = ap.parse_args()

    if args.no_color:
        set_rich(False)

    reg = Registry(REGISTRY_PATH)
    # allow --only-ignored to work without --scan
    if args.only_ignored:
        args.scan = args.scan or not args.set

    if args.diff:
        diff_configs(args.file, args.diff, reg)
        return 0

    try:
        data, size = detect_and_load(args.file)
    except Refused as exc:
        print("REFUSED: %s" % exc, file=sys.stderr)
        return 2

    src = dict(data)

    rows, absent = scan(data, reg)

    if args.only_ignored:
        ign = [r for r in rows if r["status"] == "IGNORED-BY-3.10.2"]
        if RICH:
            print_ignored_rich(ign)
            return 0
        print("IGNORED-BY-3.10.2: %d keys (macOS / SEB 2.x legacy, not read by 3.10.2)" % len(ign))
        for r in ign:
            print("   %-44s %s" % (r["key"], fmt_raw(r["raw"])))
        return 0

    print_report(data, rows, absent, reg, size, args.file)

    if check_encryption(data):
        print("stopping before the toggle phase: %s = True (sec 3.2)" % ENCRYPTION_KEY)
        return 3

    # resolve intended changes
    intended = {}
    if args.unlock_all:
        intended.update(build_unlock(data))
        print("  RELAXATION PROFILE: %d keys queued" % len(intended))
    for s in args.set:
        k, v = parse_set_arg(s, reg)
        if k not in src and not args.add_missing:
            print("REFUSED: %s is not in the file; pass --add-missing to add it (sec 4.3)" % k, file=sys.stderr)
            return 2
        if k in src and isinstance(src[k], bool) and not isinstance(v, bool):
            print("REFUSED: %s is a boolean; got %r" % (k, v), file=sys.stderr)
            return 2
        intended[k] = v

    entries = build_menu(rows, reg, args.category)

    if not intended and not args.scan:
        intended = interactive_toggle(entries, data)

    if not intended:
        if args.out:
            # sec 9.1 Test A - a no-op round trip still exercises the write path.
            # If this is not byte-identical in content, the writer is lossy.
            out_path = Path(args.out)
            with out_path.open("wb") as fh:
                plistlib.dump(src, fh, fmt=plistlib.FMT_XML)
            ok, errors, stats = verify(src, args.file, out_path, {}, args.add_missing)
            print("WRITE (no-op round trip): %s" % out_path)
            print("  keys %d -> %d" % (stats["src_keys"], stats["out_keys"]))
            if ok:
                print("  VERIFIED: write path is lossless (sec 9.1 Test A)")
                return 0
            print("  ASSERTION FAILURE")
            for e in errors:
                print("    %s" % e)
            return 4
        print("no changes selected. nothing written.")
        return 0

    # sec 6.5 preview
    if RICH:
        print_preview_rich(intended, src)
    else:
        print("PREVIEW DIFF")
        print("-" * 70)
        for k, v in sorted(intended.items()):
            if k in src:
                print("   %-38s %s -> %s" % (k, fmt_raw(src[k]), fmt_raw(v)))
            else:
                print("   %-38s (absent) -> %s        [ADDITION]" % (k, fmt_raw(v)))
        added_preview = [k for k in intended if k not in src]
        if added_preview:
            print("   additions: %s  <- these change the config's identity" % added_preview)

    if not args.yes:
        ans = input("write? [y/N] ").strip().lower()
        if ans != "y":
            print("aborted. nothing written.")
            return 1

    out_path = Path(args.out) if args.out else Path(args.file).with_suffix("").with_name(
        Path(args.file).stem + ".modified.seb")
    if out_path.resolve() == Path(args.file).resolve():
        print("REFUSED: refusing to write in place (sec 7)", file=sys.stderr)
        return 2

    out_path, added = write_output(data, intended, args.file, out_path, args.add_missing, reg)
    ok, errors, stats = verify(src, args.file, out_path, intended, args.add_missing)

    if RICH:
        _write_report_rich(out_path, stats)
    else:
        print()
        print("WRITE: %s" % out_path)
        print("  bytes    : %d -> %d (%+d)" % (stats["src_bytes"] or 0, stats["out_bytes"],
                                               stats["out_bytes"] - (stats["src_bytes"] or 0)))
        print("  keys     : %d -> %d (%+d)" % (stats["src_keys"], stats["out_keys"],
                                               stats["out_keys"] - stats["src_keys"]))
        if stats["added"]:
            print("  added    : %s" % stats["added"])

    if ok:
        print("  VERIFIED: all 5 assertions pass (sec 7)")
        return 0
    print("  ASSERTION FAILURE - deleting output")
    for e in errors:
        print("    %s" % e)
    out_path.unlink(missing_ok=True)
    return 4


if __name__ == "__main__":
    sys.exit(main())
